# math.e
# Возвращает значение числа Эйлера (e ≈ 2.71828), которое служит основанием натурального логарифма.
# Эта константа является фундаментальной в задачах, описывающих экспоненциальный рост или затухание,
# например, в сложных процентных расчетах, физике и биологии.

import math

# Пример использования в формуле непрерывного начисления процентов A = P * e^(rt)
# где P - основная сумма, r - ставка, t - время
principal = 1000
rate = 0.05
time = 2
final_amount = principal * math.pow(math.e, rate * time)

print(f"Значение e: {math.e}")
print(f"Итоговая сумма: {final_amount}")
