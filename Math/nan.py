# math.nan
# Означает "Не число" (Not a Number). Это специальное значение с плавающей точкой, которое является результатом
# математически неопределенных операций, таких как деление нуля на ноль или извлечение квадратного корня из отрицательного числа.

import math

a = 0.0
b = 0.0
result = a / b
print(f"Результат 0.0 / 0.0: {result}")

# Стандартный оператор сравнения '==' не работает для nan
# print(result == math.nan) # Выведет False

# Для проверки на nan следует использовать функцию math.isnan()
is_nan = math.isnan(result)
print(f"Является ли результат 'не числом'? {is_nan}")
# Важно отметить, что math.nan никогда не равен самому себе. Для корректной проверки
# является ли значение nan всегда используйте функцию math.isnan()
