# math.pi
# Представляет математическую константу π (пи), которая является отношением длины 
# окружности к её диаметру. Это одна из самых востребованных констант в научных и инженерных расчетах.

import math

radius = 10
# Расчет площади круга по формуле S = π * r^2
area = math.pi * (radius ** 2)
print(f"Значение Pi: {math.pi}")
print(f"Площадь круга с радиусом {radius}: {area}")
