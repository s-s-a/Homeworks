# math.log(x[, base])
# Вычисляет логарифм x. Если второй аргумент base (основание логарифма) указан, вычисляется логарифм по этому основанию. 
# Если base не указан, вычисляется натуральный логарифм (по основанию e).

import math
# Логарифм 1000 по основанию 10
print(math.log(1000, 10)) # Вывод: 3.0

# Натуральный логарифм
print(math.log(math.e))    # Вывод: 1.0
