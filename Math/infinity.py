# math.inf
# Представляет положительную бесконечность в виде числа с плавающей точкой. Это не число в привычном понимании, 
# а концепция, обозначающая значение, большее любого конечного числа. Для получения отрицательной бесконечности 
# используется выражение -math.inf. Бесконечность полезна в алгоритмах для задания начальных значений при поиске 
# минимумов или максимумов.

import math

# Поиск минимального значения в списке
numbers = [10, 5, 100, -2, 50]
smallest_number = math.inf

for num in numbers:
    if num < smallest_number:
        smallest_number = num

print(f"Самое маленькое число: {smallest_number}")