# Задача 2 (Легкая+): Фабрика декораторов `@prefix`
# Условие:
# Напишите фабрику декораторов prefix, которая принимает строку-префикс. Декоратор, который она
# возвращает, должен добавлять этот префикс к результату выполнения декорируемой функции.

# Требования:
# Декорируемая функция должна возвращать строку.
# Декоратор должен принимать один аргумент p (строку-префикс).

# Пример использования:

@prefix(p="[LOG]: ")
def get_status(code):
    return f"Status code is {code}"

print(get_status(200)) # Выведет: [LOG]: Status code is 200
print(get_status(404)) # Выведет: [LOG]: Status code is 404
