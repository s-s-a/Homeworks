import random

def task_5_open_lootbox(items: dict[str, int]) -> str:
    """
    Функция, которая имитирует открытие "лутбокса" (контейнера с наградами в играх).
    Функция должна возвращать один предмет с учётом его "веса" или шанса выпадения.

    Args:
        items (dict[str, int]): Словарь, где ключ (str) — название предмета, а значение (int) — его вес.
                                Чем больше вес, тем выше шанс выпадения.

    Returns:
        str: Строка с названием одного выпавшего предмета.
    """
    loot = list(items.keys())
    chances = list(x * 0.01 for x in items.values())
    # loot = ["Обычный", "Редкий", "Эпический"]
    # Шансы: 80% для обычного, 15% для редкого, 5% для эпического
    # chances = [0.80, 0.15, 0.05]

    return random.choices(loot, weights=chances, k=1)[0]

